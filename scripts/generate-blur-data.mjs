import { promises as fs } from 'node:fs';
import path from 'node:path';
import { getPlaiceholder } from 'plaiceholder';
import sharp from 'sharp';

const imageRoot = path.join(process.cwd(), 'public', 'images');
const generatedDir = path.join(process.cwd(), 'public', 'images', 'generated');
const outputPath = path.join(process.cwd(), 'src', 'lib', 'images', 'generated', 'blur-data.ts');
const supportedExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif']);
const widths = [800, 1600, 2400];

async function pathExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function listImages(directory) {
  if (!(await pathExists(directory))) return [];
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(directory, entry.name);
      // skip the generated output folder so we don't recurse into our own output
      if (entryPath === generatedDir) return [];
      if (entry.isDirectory()) return listImages(entryPath);
      if (entry.isFile() && supportedExtensions.has(path.extname(entry.name).toLowerCase())) {
        return entryPath;
      }
      return [];
    })
  );
  return files.flat();
}

function toPublicPath(filePath) {
  const relativePath = path.relative(path.join(process.cwd(), 'public'), filePath);
  return `/${relativePath.split(path.sep).join('/')}`;
}

async function generateResizedVariants(imagePath) {
  const buffer = await fs.readFile(imagePath);
  const metadata = await sharp(buffer).metadata();
  const baseName = path.basename(imagePath, path.extname(imagePath));
  const relativeDir = path.relative(imageRoot, path.dirname(imagePath));

  await fs.mkdir(path.join(generatedDir, relativeDir), { recursive: true });

  const generatedWidths = [];

  for (const targetWidth of widths) {
    if (metadata.width && targetWidth > metadata.width) continue;

    const outFileName = `${baseName}-${targetWidth}.webp`;
    const outPath = path.join(generatedDir, relativeDir, outFileName);

    await sharp(buffer)
      .resize({ width: targetWidth })
      .webp({ quality: 78 })
      .toFile(outPath);

    generatedWidths.push(targetWidth);
  }

  // always include the original resolution as a fallback, so there's at least one entry
  if (generatedWidths.length === 0 && metadata.width) {
    generatedWidths.push(metadata.width);
  }

  return {
    widths: generatedWidths,
    width: metadata.width ?? null,
    height: metadata.height ?? null,
  };
}

async function main() {
  const imagePaths = await listImages(imageRoot);
  const blurEntries = {};
  const manifestEntries = {};

  for (const imagePath of imagePaths) {
    const buffer = await fs.readFile(imagePath);
    const { base64 } = await getPlaiceholder(buffer, { size: 12 });
    const publicPath = toPublicPath(imagePath);

    blurEntries[publicPath] = base64;
    manifestEntries[publicPath] = await generateResizedVariants(imagePath);
  }

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(
    outputPath,
    `// This file is generated by scripts/generate-blur-data.mjs.\n` +
      `// Do not edit by hand.\n\n` +
      `export const blurData = ${JSON.stringify(blurEntries, null, 2)} as const;\n\n` +
      `export const imageManifest = ${JSON.stringify(manifestEntries, null, 2)} as const;\n\n` +
      `export type BlurImagePath = keyof typeof blurData;\n`,
    'utf8'
  );

  console.log(`Generated blur data + responsive variants for ${imagePaths.length} image(s).`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});